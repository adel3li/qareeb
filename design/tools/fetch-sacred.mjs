// Copies the sacred texts used in the design mockups from their sources, verbatim.
// Nothing here is typed: verses come from api.quran.com (text_qpc_hafs, the King Fahd
// Complex text the Madina Mushaf font is built for), hadith from the open hadith-api
// dataset (from sunnah.com), each by reference.
//
// Excerpts (the part of a verse or narration that is the dua) are cut by word index or
// by the source's own quotation marks, FOR THE MOCKUPS ONLY. In the real cards the
// excerpt boundaries are the reviewer's decision (docs/handoff/03-content-model.md §4).
//
// Usage: node design/tools/fetch-sacred.mjs > design/content/sacred.json

const VERSES = ['1:6', '1:7', '2:186', '2:286', '3:8', '21:87'];
const HADITH = { muslim: ['2705', '2721'] };

async function json(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r.json();
}

const out = {
  _about:
    'Generated by design/tools/fetch-sacred.mjs. Copied verbatim from the sources below; do not edit by hand. Excerpts are cut mechanically for the mockups only.',
  _sources: {
    quran: 'https://api.quran.com/api/v4/quran/verses/qpc_hafs (text_qpc_hafs)',
    hadith: 'https://cdn.jsdelivr.net/gh/fawazahmed0/hadith-api@1/editions/ara-<collection>.min.json',
  },
  quran: {},
  hadith: {},
  excerpts: {},
};

for (const key of VERSES) {
  const data = await json(`https://api.quran.com/api/v4/quran/verses/qpc_hafs?verse_key=${key}`);
  const v = data.verses.find((x) => x.verse_key === key);
  if (!v) throw new Error(`verse ${key} not found`);
  out.quran[key] = v.text_qpc_hafs;
}

for (const [coll, nums] of Object.entries(HADITH)) {
  const data = await json(`https://cdn.jsdelivr.net/gh/fawazahmed0/hadith-api@1/editions/ara-${coll}.min.json`);
  for (const n of nums) {
    const h = data.hadiths.find((x) => String(x.arabicnumber ?? '').split('.')[0] === n);
    if (!h) throw new Error(`${coll} ${n} not found`);
    if (h.text.includes('�')) throw new Error(`${coll} ${n} has a corrupted character in the source`);
    out.hadith[`${coll}:${n}`] = h.text;
  }
}

// Mockup excerpts, cut mechanically (never typed).
const words = (s) => s.split(' ');
const bare = (s) => s.replace(/\p{M}/gu, '');
// Yunus, 21:87: from the word after «… ٱلظلمت أن» to the end of the verse
// (located by its bare letters, so diacritic order does not matter).
{
  const w = words(out.quran['21:87']);
  const i = w.findIndex((x) => bare(x) === 'ٱلظلمت');
  if (i < 0) throw new Error('anchor word not found in 21:87');
  out.excerpts['21:87'] = w.slice(i + 2).join(' ');
}
// Muslim 2721: the words between the source's own quotation marks.
{
  const t = out.hadith['muslim:2721'];
  const m = t.match(/"‏?\s*([^"]+?)\s*‏?"/);
  if (!m) throw new Error('no quoted dua in muslim:2721');
  out.excerpts['muslim:2721'] = m[1].replace(/[‏\s]+$/u, '').trim();
}

process.stdout.write(JSON.stringify(out, null, 2) + '\n');
